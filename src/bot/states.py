"""
FSM-состояния бота. Соответствуют UX-флоу из architecture_and_plan.md, раздел 8.

Разбито на несколько StatesGroup вместо одной большой — потому что это разные,
не пересекающиеся по времени сценарии: онбординг происходит один раз (или при
добавлении ещё одного сайта), а редактирование ссылки/добавление заметки/смена
рабочего окна — это отдельные, короткие сценарии из меню, которые могут
начаться в любой момент, когда пользователь не находится в онбординге.

Когда FSM-состояние не установлено (aiogram: state=None) — это и есть "IDLE"
из схемы в архитектуре: обычный режим, доступно меню, никакого текста от
пользователя не ждём в особом контексте.

Данные, которые нужно передавать между шагами одного сценария (например,
"о каком сайте идёт речь" между вводом ссылки и выбором интервала), хранятся
через FSMContext.update_data() / get_data() — не здесь, но комментарии ниже
фиксируют, что ожидается в data на каждом шаге, чтобы не путаться при
написании handlers.
"""

from aiogram.fsm.state import State, StatesGroup


class OnboardingStates(StatesGroup):
    """
    Первое знакомство с ботом ИЛИ добавление ещё одного сайта из сценария
    "Хотите добавить ещё один сайт для отслеживания?" — намеренно один и тот
    же набор состояний для обоих случаев, механика идентична.

    Ожидаемые данные в FSMContext на разных шагах:
      awaiting_link:
        (данных ещё нет — это первый шаг сценария)

      awaiting_interval:
        data['pending_site']       -> "ss_ge" | "myhome_ge" (определено по домену)
        data['pending_filter_url'] -> сырая ссылка, как прислал пользователь
        (валидация уже прошла успешно на этом шаге — иначе сюда бы не попали)
    """
    awaiting_link = State()
    awaiting_interval = State()
    ask_add_more = State()


class EditLinkStates(StatesGroup):
    """
    Меню -> "Отредактировать ссылку". Отдельная группа от OnboardingStates,
    хотя логика валидации переиспользуется (см. handlers/link.py) — потому что
    семантически это разные сценарии: тут редактируется УЖЕ существующая
    подписка, а не создаётся новая.

    Ожидаемые данные:
      awaiting_new_link:
        data['subscription_id'] -> какую подписку редактируем (проставляется
                                    ДО входа в это состояние, при нажатии
                                    кнопки "Редактировать" у конкретной подписки)
    """
    awaiting_new_link = State()


class AddNoteStates(StatesGroup):
    """Меню -> "Добавить заметку для разработчика". Простой одношаговый ввод текста."""
    awaiting_note_text = State()


class WorkHoursStates(StatesGroup):
    """
    Меню -> "Изменить рабочее окно бота".

    ВАЖНО (см. architecture_and_plan.md, раздел 7): пользователь вводит время
    в ТБИЛИССКОМ времени (UTC+4), конвертация в UTC для хранения в БД
    происходит в handler'е на шаге сохранения, не раньше.

    Два последовательных шага (сначала начало, потом конец) вместо одного
    сообщения с двумя временами — проще для пользователя на мобильном полю
    (не нужно парсить произвольный текстовый ввод с двумя значениями сразу).

    Ожидаемые данные:
      awaiting_end_time:
        data['work_hours_start_tbilisi'] -> "HH:MM", введённое на предыдущем шаге,
                                             ещё в тбилисском времени, не в UTC
    """
    awaiting_start_time = State()
    awaiting_end_time = State()